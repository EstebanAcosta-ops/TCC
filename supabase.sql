-- Ejecuta todo este script en Supabase > SQL Editor > New query.
-- Para la demo se guardan los datos públicos de contacto dentro de cada publicación.
-- No almacenes contraseñas en esta tabla: Supabase Auth gestiona la autenticación.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  seller_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 90),
  price numeric(12,2) not null check (price >= 0),
  category text not null default 'Otros' check (category in ('Tecnología','Hogar','Moda','Otros')),
  image_url text not null,
  description text not null default '',
  seller_name text not null,
  seller_contact text not null,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

drop policy if exists "Anyone can read products" on public.products;
create policy "Anyone can read products"
on public.products for select
to anon, authenticated
using (true);

drop policy if exists "Users can insert their own products" on public.products;
create policy "Users can insert their own products"
on public.products for insert
to authenticated
with check (auth.uid() = seller_id);

drop policy if exists "Users can update their own products" on public.products;
create policy "Users can update their own products"
on public.products for update
to authenticated
using (auth.uid() = seller_id)
with check (auth.uid() = seller_id);

drop policy if exists "Users can delete their own products" on public.products;
create policy "Users can delete their own products"
on public.products for delete
to authenticated
using (auth.uid() = seller_id);

create index if not exists products_created_at_idx on public.products (created_at desc);
create index if not exists products_seller_id_idx on public.products (seller_id);
